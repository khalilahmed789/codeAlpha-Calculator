const display = document.querySelector("#display");
function writeValue(value) {
  display.value += value;
}

function eraseAll() {
  display.value = "";
}

function deleteLast() {
  display.value = display.value.slice(0, -1);
}

function calculate() {
  try {
    display.value = eval(display.value);
  } catch (error) {
    display.value = "Error";
  }
}
